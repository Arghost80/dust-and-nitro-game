from generate_six_pro_circuits import generate_six_tracks
import json

print("1. Generating 6 pro circuits...")
new_tracks = generate_six_tracks()

print("2. Reading tracks_data.js...")
with open('tracks_data.js', 'r', encoding='utf-8') as f:
    text = f.read()

end_idx = text.rfind('}};') + 2
start_idx = text.find('{')
all_tracks = json.loads(text[start_idx:end_idx])

# Replace the 6 tracks
for tid, tdata in new_tracks.items():
    print(f"Replacing track: {tid}")
    all_tracks[tid] = tdata

# Also check story chapters track id mapping
# In STORY_CHAPTERS, let's make sure the track ids match:
# 'sarthe_endurance' -> 'sarthe' or 'sarthe_endurance'
# Let's also provide aliases so both 'sarthe' and 'sarthe_endurance' work:
all_tracks['sarthe'] = all_tracks['sarthe_endurance']

# Output updated tracks_data.js
js_output = "// ===== AUTOGENERATED DUSTRAC TRACKS DATA: 28 CIRCUITOS PRO =====\nconst DustracTracks = " + json.dumps(all_tracks, separators=(',', ':')) + ";\n\nif (typeof window !== 'undefined') {\n    window.DustracTracks = DustracTracks;\n}\nif (typeof module !== 'undefined' && module.exports) {\n    module.exports = DustracTracks;\n}\n"

with open('tracks_data.js', 'w', encoding='utf-8') as f:
    f.write(js_output)

print("3. tracks_data.js written successfully!")
