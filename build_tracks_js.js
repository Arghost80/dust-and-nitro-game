const fs = require('fs');

const data = JSON.parse(fs.readFileSync('tracks_data.json', 'utf8'));
const content = `// ===== AUTOGENERATED DUSTRAC TRACKS DATA: ${Object.keys(data).length} CIRCUITOS PRO =====\nconst DustracTracks = ${JSON.stringify(data)};\n\nif (typeof window !== 'undefined') {\n    window.DustracTracks = DustracTracks;\n}\nif (typeof module !== 'undefined' && module.exports) {\n    module.exports = DustracTracks;\n}\n`;

fs.writeFileSync('tracks_data.js', content, 'utf8');
console.log('Successfully written tracks_data.js:', fs.statSync('tracks_data.js').size, 'bytes');
