let currentLang = 'es';

function setLanguage(lang) {
    if (TRANSLATIONS[lang]) {
        currentLang = lang;
        try { localStorage.setItem('dustrac_lang', lang); } catch(e) {}
    }
}

function getSavedLanguage() {
    try {
        const saved = localStorage.getItem('dustrac_lang');
        if (saved && TRANSLATIONS[saved]) return saved;
    } catch(e) {}
    return 'es';
}

